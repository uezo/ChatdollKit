// Regenerate with Node.js, passing the upstream engine and profile paths explicitly:
// node generate-mfcc-fixtures.cjs /path/to/mfcc-lipsync.js /path/to/default-female.json
// The generated C# fixture is self-contained: tests do not load these source paths.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');

if (process.argv.length !== 4) throw new Error('Expected engine JS path and profile JSON path');
const source = fs.readFileSync(process.argv[2], 'utf8');
const profileSource = fs.readFileSync(process.argv[3], 'utf8');
const Engine = vm.runInNewContext(source + '\nMFCCLipSyncEngine;');
const profile = JSON.parse(profileSource);
const hash = text => crypto.createHash('sha256').update(text).digest('hex');
const number = value => Number.isInteger(value) ? `${value}.0` : `${value}`;

// Integer arithmetic followed by a binary division gives identical Float32 PCM in C#/JS.
// Mix triangle waves with different formant-like frequencies and seeded background noise.
function triangle(frame, frequency, sampleRate) {
    const phase = Math.floor(frame * frequency * 65536 / sampleRate) % 65536;
    return phase < 32768 ? phase - 16384 : 49152 - phase;
}
function pcm(sampleRate) {
    const samples = new Float32Array(Math.floor(sampleRate / 4));
    let state = 0x12345678;
    for (let i = 0; i < samples.length; i++) {
        state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
        const noise = (state >>> 24) - 128;
        samples[i] = (triangle(i, 137, sampleRate) * 3
            + triangle(i, 719, sampleRate) * 2
            + triangle(i, 1223, sampleRate)
            + triangle(i, 2549, sampleRate) + noise * 512) / 4194304;
    }
    return samples;
}

const cases = [];
for (const [compareMethod, useStandardization] of [[2, false], [0, false], [1, false], [0, true], [1, true]]) {
for (const sampleRate of (compareMethod === 2 && !useStandardization ? [16000, 24000, 44100, 48000] : [16000])) {
    for (const [name, samplePosition, timeOffsetSeconds] of [
        ['full', Math.floor(sampleRate * 0.18), 0],
        ['beginning', Math.floor(sampleRate * 0.01), 0],
        ['positive-offset', Math.floor(sampleRate * 0.12), 0.017],
        ['negative-offset', Math.floor(sampleRate * 0.12), -0.013],
    ]) {
        if ((compareMethod !== 2 || useStandardization) && name !== 'full') continue;
        const engine = new Engine({ profile: { ...profile, compareMethod, useStandardization }, timeOffsetSec: timeOffsetSeconds });
        const audio = { pcm: pcm(sampleRate), sampleRate, samplePosition };
        const features = engine.extractMfcc(audio);
        const result = engine.processAudioData(audio);
        if (!Object.values(result.visemes).some(weight => weight > 0)) {
            throw new Error(`Fixture ${name}/${sampleRate} must exercise nonzero phoneme scores`);
        }
        cases.push({ name: `${sampleRate}-${name}-method${compareMethod}-standardize${useStandardization}`, sampleRate, samplePosition,
            compareMethod, useStandardization,
            timeOffsetSeconds, mfcc: Array.from(features.mfcc), rawVolume: features.rawVolume,
            volume: engine._normalizeVolume(features.rawVolume), ...result });
    }
}
}

